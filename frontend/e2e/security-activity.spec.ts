import { createHmac } from 'node:crypto'
import { expect, test } from '@playwright/test'

const password = 'Local-preview-only-123!'
function totp(secret: string) {
  const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567'
  const bits = [...secret].map(char => alphabet.indexOf(char).toString(2).padStart(5, '0')).join('')
  const key = Buffer.from(bits.match(/.{8}/g)!.map(byte => parseInt(byte, 2)))
  const counter = Buffer.alloc(8); counter.writeBigUInt64BE(BigInt(Math.floor(Date.now() / 30000)))
  const mac = createHmac('sha1', key).update(counter).digest()
  return String((mac.readUInt32BE(mac[19] & 15) & 0x7fffffff) % 1000000).padStart(6, '0')
}

test('real browser enrolls MFA, requires second factor, uses backups and disables securely', async ({ page }) => {
  const email = `mfa-e2e-${Date.now()}@example.com`
  expect((await page.request.post('/auth/register', { data: { name: 'MFA E2E', email, password } })).status()).toBe(201)
  await page.goto('/sign-in')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Welcome, MFA E2E' })).toBeVisible()
  await page.goto('/account')
  await page.getByRole('button', { name: 'Set up authenticator', exact: true }).click()
  await page.getByLabel('Confirm account password').fill(password)
  await page.getByRole('button', { name: 'Confirm password and get QR code' }).click()
  const section = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Two-factor sign-in', exact: true }) }).last()
  const secret = await section.locator('code').first().textContent()
  await page.getByLabel('Code from authenticator app', { exact: true }).fill(totp(secret!))
  await page.getByRole('button', { name: 'Enable two-factor sign-in', exact: true }).click()
  const backupRegion = page.getByRole('region', { name: 'Your backup codes' })
  await expect(backupRegion.locator('li code')).toHaveCount(10)
  const backups = await backupRegion.locator('li code').allTextContents()
  await page.getByRole('button', { name: 'I saved my backup codes' }).click()
  await page.getByRole('button', { name: 'Log out', exact: true }).click()
  await page.goto('/sign-in')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Two-factor sign-in', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Welcome, MFA E2E' })).toHaveCount(0)
  await page.getByLabel('Authenticator or backup code', { exact: true }).fill(backups[0])
  await page.getByRole('button', { name: 'Verify and sign in' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome, MFA E2E' })).toBeVisible()
  await page.goto('/account')
  await page.getByLabel('Current authenticator or unused backup code', { exact: true }).fill(backups[1])
  await page.getByRole('button', { name: 'Turn off two-factor sign-in' }).click()
  await expect(page.getByRole('button', { name: 'Set up authenticator' })).toBeVisible()
  expect(await page.evaluate(() => [localStorage.length, sessionStorage.length])).toEqual([0, 0])
})

test('Google-only synthetic account receives a local code and adds a password through the browser', async ({ page, context }) => {
  const email = 'qa-google@example.com'
  await page.goto('/sign-in#forgot-password')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByRole('button', { name: 'Request password reset' }).click()
  await expect(page.getByLabel('Code from your email')).toBeVisible()
  const inbox = await context.newPage()
  await inbox.goto('http://127.0.0.1:8125/')
  const message = inbox.locator('article').filter({ has: inbox.getByRole('heading', { name: email, exact: true }) }).first()
  await expect(message.locator('code')).toBeVisible()
  const code = await message.locator('code').textContent()
  await page.getByLabel('Code from your email').fill(code!)
  await page.getByRole('button', { name: 'Verify code', exact: true }).click()
  await page.getByLabel('New password', { exact: true }).fill(password)
  await page.getByLabel('Confirm password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Set new password', exact: true }).click()
  await expect(page.getByText(/password has been changed/i)).toBeVisible()
  await inbox.close()
})

